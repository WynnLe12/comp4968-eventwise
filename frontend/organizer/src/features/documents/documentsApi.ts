import { apiUrl } from "../../services/apiConfig";
import { requireAuthSession } from "../auth/services/authService";

export interface EventDocument {
    documentId: string;
    eventId: string;
    filename: string;
    contentType: string;
    sizeBytes: string;
    uploadedAt: string;
}

export interface UploadUrlResponse {
    uploadUrl: string;
    uploadFields: Record<string, string>;
    uploadToken: string;
    expiresIn: number;
}

export interface DownloadUrlResponse {
    document: EventDocument;
    downloadUrl: string;
    expiresIn: number;
}

export interface DeleteDocumentResponse {
    deleted: boolean;
    storageCleanupPending: boolean;
}

async function documentRequest<T>(
    path: string,
    method = "GET",
    body?: unknown,
): Promise<T> {
    // Reuse the team's existing Cognito authentication.
    const identity = await requireAuthSession();
    const token = identity.session.tokens?.accessToken;

    if (!token) {
        throw new Error(
            "Your session has expired. Please sign in again.",
        );
    }

    const response = await fetch(apiUrl(path), {
        method,
        headers: {
            Authorization: `Bearer ${token.toString()}`,
            ...(body !== undefined
                ? { "Content-Type": "application/json" }
                : {}),
        },
        ...(body !== undefined
            ? { body: JSON.stringify(body) }
            : {}),
    });

    const result: unknown = await response.json().catch(() => null);

    if (response.status === 401) {
        throw new Error(
            "Your session has expired. Please sign in again.",
        );
    }

    if (!response.ok) {
        const error =
            result && typeof result === "object"
                ? (result as { error?: string })
                : null;

        throw new Error(
            error?.error ?? `Request failed (${response.status})`,
        );
    }

    return result as T;
}

function documentsPath(eventId: string): string {
    return `/events/${encodeURIComponent(eventId)}/documents`;
}

// List documents belonging to the selected event.
export async function fetchDocuments(
    eventId: string,
): Promise<EventDocument[]> {
    const response = await documentRequest<{
        documents: EventDocument[];
    }>(documentsPath(eventId));

    return response.documents;
}

// Ask Lambda for a temporary S3 upload URL.
export function requestDocumentUpload(
    eventId: string,
    file: File,
): Promise<UploadUrlResponse> {
    return documentRequest(
        `${documentsPath(eventId)}/upload-url`,
        "POST",
        {
            filename: file.name,
            contentType: file.type,
            sizeBytes: file.size,
        },
    );
}

// Upload directly to S3 using the presigned URL.
export async function uploadFileToS3(
    file: File,
    uploadUrl: string,
    uploadFields: Record<string, string>,
): Promise<void> {
    const formData = new FormData();

    // Include every field generated by the AWS SDK.
    for (const [name, value] of Object.entries(uploadFields)) {
        formData.append(name, value);
    }

    // S3 requires the file to be the last form field.
    formData.append("file", file);

    const response = await fetch(uploadUrl, {
        method: "POST",
        body: formData,
    });

    // Successful S3 POST requests commonly return HTTP 204.
    if (!response.ok) {
        throw new Error(
            `File upload failed (${response.status}).`,
        );
    }
}

// Confirm the uploaded file and save metadata in MySQL.
export function completeDocumentUpload(
    eventId: string,
    uploadToken: string,
): Promise<{ documentId: string; message: string }> {
    return documentRequest(
        `${documentsPath(eventId)}/complete`,
        "POST",
        { uploadToken },
    );
}

// Complete upload workflow: Lambda → S3 → Lambda.
export async function uploadDocument(
    eventId: string,
    file: File,
): Promise<{ documentId: string; message: string }> {
    // Step 1: Request upload authorization from Lambda.
    const {
        uploadUrl,
        uploadFields,
        uploadToken,
    } = await requestDocumentUpload(eventId, file);

    // Step 2: Upload directly to private S3.
    await uploadFileToS3(
        file,
        uploadUrl,
        uploadFields,
    );

    // Step 3: Verify the object and save metadata in RDS.
    return completeDocumentUpload(eventId, uploadToken);
}

// Get an authorized temporary URL for a document.
export function getDocumentDownloadUrl(
    eventId: string,
    documentId: string,
): Promise<DownloadUrlResponse> {
    return documentRequest(
        `${documentsPath(eventId)}/${encodeURIComponent(documentId)}/download`,
    );
}

// Delete a document through Lambda.
export function deleteDocument(
    eventId: string,
    documentId: string,
): Promise<DeleteDocumentResponse> {
    return documentRequest(
        `${documentsPath(eventId)}/${encodeURIComponent(documentId)}`,
        "DELETE",
    );
}
